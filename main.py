def generate_visualizations(df, numeric_cols, categorical_cols):
    section("3. TRENDS, PATTERNS & ANOMALIES (VISUALIZATIONS)")
    os.makedirs(PLOTS_DIR, exist_ok=True)

    # --- Histograms for numeric columns ---
    if numeric_cols:
        n = len(numeric_cols)
        ncols = 3
        nrows = int(np.ceil(n / ncols))
        fig, axes = plt.subplots(nrows, ncols, figsize=(6 * ncols, 4 * nrows))
        axes = np.array(axes).reshape(-1)
        for i, col in enumerate(numeric_cols):
            sns.histplot(df[col].dropna(), kde=True, ax=axes[i], color="steelblue")
            axes[i].set_title(f"Distribution of {col}")
        for j in range(i + 1, len(axes)):
            fig.delaxes(axes[j])
        plt.tight_layout()
        path = os.path.join(PLOTS_DIR, "histograms.png")
        plt.savefig(path, dpi=150)
        plt.close()
        print(f"Saved histograms -> {path}")

    # --- Boxplots for outlier detection ---
    if numeric_cols:
        n = len(numeric_cols)
        ncols = 3
        nrows = int(np.ceil(n / ncols))
        fig, axes = plt.subplots(nrows, ncols, figsize=(6 * ncols, 4 * nrows))
        axes = np.array(axes).reshape(-1)
        for i, col in enumerate(numeric_cols):
            sns.boxplot(x=df[col], ax=axes[i], color="salmon")
            axes[i].set_title(f"Boxplot of {col} (outlier check)")
        for j in range(i + 1, len(axes)):
            fig.delaxes(axes[j])
        plt.tight_layout()
        path = os.path.join(PLOTS_DIR, "boxplots.png")
        plt.savefig(path, dpi=150)
        plt.close()
        print(f"Saved boxplots -> {path}")

    # --- Correlation heatmap ---
    if len(numeric_cols) >= 2:
        plt.figure(figsize=(10, 8))
        corr = df[numeric_cols].corr()
        sns.heatmap(corr, annot=True, fmt=".2f", cmap="coolwarm", center=0, square=True)
        plt.title("Correlation Heatmap (Numeric Features)")
        plt.tight_layout()
        path = os.path.join(PLOTS_DIR, "correlation_heatmap.png")
        plt.savefig(path, dpi=150)
        plt.close()
        print(f"Saved correlation heatmap -> {path}")

    # --- Bar charts for categorical columns (top 10 categories) ---
    for col in categorical_cols[:5]:  # cap to avoid excessive plots
        plt.figure(figsize=(10, 6))
        top_vals = df[col].value_counts().head(10)
        sns.barplot(x=top_vals.values, y=top_vals.index.astype(str), color="teal")
        plt.title(f"Top categories in {col}")
        plt.xlabel("Count")
        plt.tight_layout()
        safe_name = "".join(c if c.isalnum() else "_" for c in col)
        path = os.path.join(PLOTS_DIR, f"barchart_{safe_name}.png")
        plt.savefig(path, dpi=150)
        plt.close()
        print(f"Saved bar chart for '{col}' -> {path}")

    # --- Pairplot (sampled) for a quick multi-variable relationship view ---
    if 2 <= len(numeric_cols) <= 6:
        sample_df = df[numeric_cols].dropna()
        if len(sample_df) > 500:
            sample_df = sample_df.sample(500, random_state=42)
        pair = sns.pairplot(sample_df, diag_kind="kde", plot_kws={"alpha": 0.5, "s": 20})
        pair.fig.suptitle("Pairwise Relationships (sampled)", y=1.02)
        path = os.path.join(PLOTS_DIR, "pairplot.png")
        pair.savefig(path, dpi=150)
        plt.close()
        print(f"Saved pairplot -> {path}")

    print("\nInsight: Review histograms for skew, boxplots for outliers beyond the "
          "whiskers, and the heatmap for strongly correlated (|r| > 0.7) feature pairs.")


