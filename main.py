def print_meaningful_questions(df, numeric_cols, categorical_cols, datetime_cols):
    section("1. MEANINGFUL ANALYTICAL / BUSINESS QUESTIONS")

    questions = []

    if numeric_cols:
        questions.append(
            f"Q1. What is the central tendency and spread of key numeric metrics "
            f"({', '.join(numeric_cols[:3])}...), and do any of them show extreme outliers "
            f"that could distort downstream analysis or modeling?"
        )
    if len(numeric_cols) >= 2:
        questions.append(
            f"Q2. Which pairs of numeric variables are most strongly correlated, and could any "
            f"of these relationships indicate redundancy (multicollinearity) or a meaningful "
            f"business driver worth investigating further?"
        )
    if categorical_cols:
        questions.append(
            f"Q3. How is the data distributed across key categorical groups "
            f"({', '.join(categorical_cols[:3])}...), and are there class imbalances that "
            f"could bias downstream analysis or models?"
        )
    if categorical_cols and numeric_cols:
        questions.append(
            f"Q4. Do numeric metrics differ significantly across categories of "
            f"'{categorical_cols[0]}'? (e.g., does group membership affect the outcome?)"
        )
    if datetime_cols:
        questions.append(
            f"Q5. Is there a discernible trend or seasonality over time in "
            f"'{datetime_cols[0]}' that could inform forecasting or planning?"
        )
    else:
        questions.append(
            "Q5. Which columns have data quality issues (missing values, inconsistent types, "
            "duplicates) that must be addressed before this dataset is analysis- or model-ready?"
        )

    for q in questions:
        print(f"  - {q}")

    return questions


