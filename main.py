def main():
    csv_path = sys.argv[1] if len(sys.argv) > 1 else find_csv()
    df = load_data(csv_path)

    numeric_cols, categorical_cols, datetime_cols = classify_columns(df)

    print_meaningful_questions(df, numeric_cols, categorical_cols, datetime_cols)
    missing_report, dup_count = explore_structure(df)
    generate_visualizations(df, numeric_cols, categorical_cols)
    run_hypothesis_tests(df, numeric_cols, categorical_cols)
    data_quality_report(df, numeric_cols, missing_report, dup_count)

    section("EDA COMPLETE")
    print(f"All plots saved to the '{PLOTS_DIR}/' directory.")


if __name__ == "__main__":
    main()