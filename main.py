# 5. DATA QUALITY REPORT
# ----------------------------------------------------------------------------
def data_quality_report(df, numeric_cols, missing_report, dup_count):
    section("5. DATA QUALITY REPORT")

    issues = []
    recommendations = []

    # Missing values
    if not missing_report.empty:
        for col, row in missing_report.iterrows():
            issues.append(f"Column '{col}' has {int(row['missing_count'])} missing values "
                          f"({row['missing_pct']}%).")
        recommendations.append(
            "Impute missing numeric values with median/mean (or a model-based imputer), and "
            "missing categorical values with mode or an explicit 'Unknown' category. "
            "Consider dropping columns with >50% missing data."
        )
    else:
        issues.append("No missing values detected.")

    # Duplicate rows
    if dup_count > 0:
        issues.append(f"{dup_count} duplicate rows detected.")
        recommendations.append("Drop duplicate rows using df.drop_duplicates() unless duplicates "
                                "are legitimate repeated observations.")
    else:
        issues.append("No duplicate rows detected.")

    # Skewness
    skewed_cols = []
    for col in numeric_cols:
        skew_val = df[col].skew()
        if abs(skew_val) > 1:
            skewed_cols.append((col, round(skew_val, 2)))
    if skewed_cols:
        for col, sk in skewed_cols:
            issues.append(f"Column '{col}' is highly skewed (skewness = {sk}).")
        recommendations.append(
            "Apply a log, sqrt, or Box-Cox transform to highly skewed numeric columns "
            "to reduce skew before modeling, especially for linear models."
        )
    else:
        issues.append("No strongly skewed numeric columns detected (|skew| <= 1).")

    # Outliers via IQR method
    outlier_cols = []
    for col in numeric_cols:
        q1, q3 = df[col].quantile([0.25, 0.75])
        iqr = q3 - q1
        lower, upper = q1 - 1.5 * iqr, q3 + 1.5 * iqr
        n_outliers = ((df[col] < lower) | (df[col] > upper)).sum()
        if n_outliers > 0:
            outlier_cols.append((col, n_outliers))
    if outlier_cols:
        for col, n in outlier_cols:
            issues.append(f"Column '{col}' has {n} potential outliers (IQR method).")
        recommendations.append(
            "Investigate outliers individually: cap/winsorize, transform, or remove them "
            "depending on whether they represent data errors or genuine extreme values."
        )
    else:
        issues.append("No significant outliers detected via IQR method.")

    # Constant / near-constant columns
    for col in df.columns:
        if df[col].nunique(dropna=True) <= 1:
            issues.append(f"Column '{col}' has only 1 unique value and carries no analytical signal.")
            recommendations.append(f"Consider dropping the constant column '{col}'.")

    # Data type mismatches (numbers stored as text, etc.)
    for col in df.select_dtypes(include="object").columns:
        sample = df[col].dropna().astype(str).head(50)
        numeric_like = sample.str.match(r"^-?\d+\.?\d*$").mean() if len(sample) else 0
        if numeric_like > 0.9:
            issues.append(f"Column '{col}' looks numeric but is stored as text/object dtype.")
            recommendations.append(f"Convert '{col}' to a numeric dtype with pd.to_numeric().")

    print("\n--- Detected Issues ---")
    for i, issue in enumerate(issues, 1):
        print(f"  {i}. {issue}")

    print("\n--- Recommendations for Preprocessing ---")
    if recommendations:
        for i, rec in enumerate(dict.fromkeys(recommendations), 1):  # dedupe, preserve order
            print(f"  {i}. {rec}")
    else:
        print("  Dataset appears clean; minimal preprocessing required.")


