def explore_structure(df):
    section("2. DATA STRUCTURE EXPLORATION")

    print(f"\nDataset dimensions: {df.shape[0]} rows x {df.shape[1]} columns\n")

    print("--- df.info() ---")
    df.info()

    print("\n--- Missing values per column ---")
    missing = df.isnull().sum()
    missing_pct = (missing / len(df) * 100).round(2)
    missing_report = pd.DataFrame({"missing_count": missing, "missing_pct": missing_pct})
    missing_report = missing_report[missing_report["missing_count"] > 0].sort_values(
        "missing_count", ascending=False
    )
    if missing_report.empty:
        print("No missing values detected.")
    else:
        print(missing_report)

    print("\n--- Duplicate rows ---")
    dup_count = df.duplicated().sum()
    print(f"Duplicate rows: {dup_count} ({dup_count / len(df) * 100:.2f}% of dataset)")

    print("\n--- df.describe() (numeric summary statistics) ---")
    print(df.describe().T)

    print("\n--- df.describe(include='object') (categorical summary) ---")
    cat_desc = df.describe(include=["object", "category", "bool"])
    if cat_desc.empty:
        print("No categorical columns detected.")
    else:
        print(cat_desc.T)

    return missing_report, dup_count


