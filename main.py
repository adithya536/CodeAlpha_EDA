# 4. HYPOTHESIS TESTING
# ----------------------------------------------------------------------------
def run_hypothesis_tests(df, numeric_cols, categorical_cols):
    section("4. HYPOTHESIS TESTING")

    results = []

    # --- Hypothesis 1: Correlation test between the two numeric columns
    #     with the strongest absolute correlation ---
    if len(numeric_cols) >= 2:
        corr = df[numeric_cols].corr().abs()
        corr_vals = corr.to_numpy(copy=True)
        np.fill_diagonal(corr_vals, 0)
        corr = pd.DataFrame(corr_vals, index=corr.index, columns=corr.columns)
        max_pair = corr.stack().idxmax()
        col_a, col_b = max_pair

        print(f"\nHypothesis 1: There is a statistically significant linear correlation "
              f"between '{col_a}' and '{col_b}'.")
        print("  H0 (null): No linear correlation exists (r = 0).")
        print("  H1 (alt) : A linear correlation exists (r != 0).")

        paired = df[[col_a, col_b]].dropna()
        r, p_value = stats.pearsonr(paired[col_a], paired[col_b])
        alpha = 0.05
        print(f"  Pearson r = {r:.4f}, p-value = {p_value:.4g}")
        if p_value < alpha:
            conclusion = (f"  Conclusion: p-value < {alpha} -> REJECT H0. There IS a statistically "
                          f"significant correlation (r={r:.2f}) between '{col_a}' and '{col_b}'.")
        else:
            conclusion = (f"  Conclusion: p-value >= {alpha} -> FAIL TO REJECT H0. No statistically "
                          f"significant correlation found between '{col_a}' and '{col_b}'.")
        print(conclusion)
        results.append(("H1: Correlation", col_a, col_b, p_value, conclusion.strip()))
    else:
        print("\nHypothesis 1: Skipped (fewer than 2 numeric columns available).")

    # --- Hypothesis 2: Group comparison - does a numeric variable differ
    #     significantly across a categorical variable's groups? ---
    if numeric_cols and categorical_cols:
        # pick the categorical column with a manageable number of groups (2-10)
        cat_col = None
        for c in categorical_cols:
            n_unique = df[c].nunique(dropna=True)
            if 2 <= n_unique <= 10:
                cat_col = c
                break
        num_col = numeric_cols[0]

        if cat_col:
            print(f"\nHypothesis 2: The mean of '{num_col}' differs significantly across "
                  f"groups of '{cat_col}'.")
            print("  H0 (null): All group means are equal.")
            print("  H1 (alt) : At least one group mean differs.")

            groups = [g.dropna().values for _, g in df.groupby(cat_col)[num_col]]
            groups = [g for g in groups if len(g) > 1]

            if len(groups) >= 2:
                f_stat, p_value = stats.f_oneway(*groups)
                alpha = 0.05
                print(f"  ANOVA F-statistic = {f_stat:.4f}, p-value = {p_value:.4g}")
                if p_value < alpha:
                    conclusion = (f"  Conclusion: p-value < {alpha} -> REJECT H0. Mean '{num_col}' "
                                  f"differs significantly across groups of '{cat_col}'.")
                else:
                    conclusion = (f"  Conclusion: p-value >= {alpha} -> FAIL TO REJECT H0. No significant "
                                  f"difference in mean '{num_col}' across groups of '{cat_col}'.")
                print(conclusion)
                results.append(("H2: Group comparison (ANOVA)", num_col, cat_col, p_value, conclusion.strip()))
            else:
                print("  Skipped: not enough groups with sufficient data for ANOVA.")
        else:
            print("\nHypothesis 2: Skipped (no categorical column with 2-10 groups found).")
    else:
        print("\nHypothesis 2: Skipped (need at least one numeric and one categorical column).")

    return results


