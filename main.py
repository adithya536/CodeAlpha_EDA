def find_csv():
    """Auto-detect a CSV file in the current folder or nearby locations if CSV_PATH is not set."""
    if CSV_PATH:
        if os.path.isabs(CSV_PATH) or os.path.exists(CSV_PATH):
            return CSV_PATH
        script_dir = os.path.dirname(os.path.abspath(__file__))
        candidate = os.path.join(script_dir, CSV_PATH)
        if os.path.exists(candidate):
            return candidate
        return CSV_PATH

    search_dirs = []
    for base in [os.getcwd(), os.path.dirname(os.path.abspath(__file__))]:
        if base and base not in search_dirs:
            search_dirs.append(base)

    candidates = []
    for base in search_dirs:
        candidates.extend(glob.glob(os.path.join(base, "*.csv")))

    script_dir = os.path.dirname(os.path.abspath(__file__))
    parent_dir = os.path.dirname(script_dir)
    if parent_dir and parent_dir not in search_dirs:
        candidates.extend(glob.glob(os.path.join(parent_dir, "*.csv")))

    seen = set()
    unique_candidates = []
    for path in candidates:
        norm = os.path.abspath(path)
        if norm not in seen:
            seen.add(norm)
            unique_candidates.append(norm)

    if not unique_candidates:
     sys.exit(
            "ERROR: No CSV file found in the current directory or nearby folders. "
            "Place a .csv file here, in the script folder, or set CSV_PATH at the top of this script."
        )
    if len(unique_candidates) > 1:
        print(f"Multiple CSVs found: {unique_candidates}. Using the first one: '{unique_candidates[0]}'")
    return unique_candidates[0]


def load_data(path):
    """Load CSV robustly, trying a couple of common encodings/separators."""
    try:
        df = pd.read_csv(path)
    except UnicodeDecodeError:
        df = pd.read_csv(path, encoding="latin1")
    print(f"Loaded '{path}' -> shape {df.shape}")
    return df


def classify_columns(df):
    """Split columns into numeric, categorical, and datetime-like groups."""
    numeric_cols = df.select_dtypes(include=[np.number]).columns.tolist()
    categorical_cols = df.select_dtypes(include=["object", "category", "bool"]).columns.tolist()

    # Try to detect datetime-like columns among object columns (by name or by parse success)
    datetime_cols = df.select_dtypes(include=["datetime64"]).columns.tolist()
    for col in list(categorical_cols):
        if any(k in col.lower() for k in ["date", "time", "year", "month", "day"]):
            try:
                parsed = pd.to_datetime(df[col], errors="coerce")
                if parsed.notna().mean() > 0.8:  # mostly parseable
                    datetime_cols.append(col)
                    categorical_cols.remove(col)
            except Exception:
                pass

    return numeric_cols, categorical_cols, datetime_cols


